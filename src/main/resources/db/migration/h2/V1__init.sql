-- Baseline schema for H2 (the default datasource).
--
-- Kept byte-for-byte compatible with what Hibernate generates for the entities, so
-- spring.jpa.hibernate.ddl-auto=validate passes on both fresh and pre-existing
-- databases (existing databases are baselined by Spring Flyway, see
-- spring.flyway.baseline-on-migrate).

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    enabled       BOOLEAN NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE,
    last_login_at TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id)
);

CREATE TABLE app_user_roles (
    user_id BIGINT NOT NULL,
    role    VARCHAR(32) NOT NULL,
    PRIMARY KEY (user_id, role)
);

CREATE TABLE audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    at         TIMESTAMP(6) WITH TIME ZONE,
    username   VARCHAR(64),
    action     VARCHAR(64) NOT NULL,
    details    VARCHAR(1024),
    outcome    VARCHAR(64),
    job_id     VARCHAR(64),
    ip         VARCHAR(64),
    user_agent VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE clamd_endpoints (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name     VARCHAR(64) NOT NULL UNIQUE,
    host     VARCHAR(255) NOT NULL,
    port     INTEGER NOT NULL,
    platform ENUM ('JVM_PLATFORM','UNIX','WINDOWS') NOT NULL,
    enabled  BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE processed_files (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    path         VARCHAR(4096) NOT NULL,
    last_modified BIGINT NOT NULL,
    size_bytes   BIGINT NOT NULL,
    sha256       VARCHAR(128),
    processed_at TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT idx_processed_path UNIQUE (path)
);

CREATE TABLE scan_jobs (
    id                 VARCHAR(64) NOT NULL,
    type               ENUM ('PATH','UPLOAD','WATCH') NOT NULL,
    status             ENUM ('FINISHED','QUEUED','RUNNING') NOT NULL,
    verdict            ENUM ('ERROR','OK','VIRUS_FOUND'),
    target             VARCHAR(2048) NOT NULL,
    stored_path        VARCHAR(1024),
    sha256             VARCHAR(128),
    size_bytes         BIGINT,
    endpoint_id        BIGINT,
    submitted_by       VARCHAR(64),
    submitted_at       TIMESTAMP(6) WITH TIME ZONE,
    started_at         TIMESTAMP(6) WITH TIME ZONE,
    finished_at        TIMESTAMP(6) WITH TIME ZONE,
    found_viruses_json TEXT,
    error_message      TEXT,
    quarantine_path    VARCHAR(2048),
    PRIMARY KEY (id)
);

CREATE TABLE watched_directories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    path        VARCHAR(2048) NOT NULL,
    endpoint_id BIGINT,
    enabled     BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

ALTER TABLE app_user_roles
    ADD CONSTRAINT fk_app_user_roles_user FOREIGN KEY (user_id) REFERENCES app_users;

ALTER TABLE scan_jobs
    ADD CONSTRAINT fk_scan_jobs_endpoint FOREIGN KEY (endpoint_id) REFERENCES clamd_endpoints;

ALTER TABLE watched_directories
    ADD CONSTRAINT fk_watched_directories_endpoint FOREIGN KEY (endpoint_id) REFERENCES clamd_endpoints;
